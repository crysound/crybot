import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import test from "node:test";
import assert from "node:assert/strict";
import { renderDrift } from "./ios-web-drift.mjs";
const exec = promisify(execFile);

test("ios web drift reports changed files, exports and members", async (t) => {
  const dir = await mkdtemp("/tmp/ios-web-drift-");
  t.after(() => rm(dir, { recursive: true, force: true }));
  await mkdir(`${dir}/shared`, { recursive: true });
  await mkdir(`${dir}/src/components`, { recursive: true });
  await exec("git", ["init", "-q"], { cwd: dir });
  await exec("git", ["config", "user.email", "test@example.com"], { cwd: dir });
  await exec("git", ["config", "user.name", "Test"], { cwd: dir });
  await writeFile(`${dir}/shared/wire.ts`, "export interface Thing {\n  old: string;\n}\n");
  await writeFile(`${dir}/shared/deleted.ts`, "export const removed = 1;\n");
  await exec("git", ["add", "."], { cwd: dir }); await exec("git", ["commit", "-qm", "base"], { cwd: dir });
  const base = (await exec("git", ["rev-parse", "HEAD"], { cwd: dir })).stdout.trim();
  await writeFile(`${dir}/shared/wire.ts`, "export interface Thing {\n  old: string;\n  added?: number;\n}\nexport type NewThing = string;\n");
  await rm(`${dir}/shared/deleted.ts`);
  await writeFile(`${dir}/src/components/added.ts`, "export async function fetchExample() {}\nexport default 1;\nexport { fetchExample as renamed, fetchExample };\nexport let mutable = 1;\n");
  await exec("git", ["add", "."], { cwd: dir }); await exec("git", ["commit", "-qm", "change"], { cwd: dir });
  const report = await renderDrift(base, dir);
  assert.match(report, /shared\/wire\.ts/);
  assert.match(report, /NewThing/);
  assert.match(report, /added/);
  assert.match(report, /## shared\/deleted\.ts\n\n- 增删行：\+0 \/ -1/);
  assert.match(report, /## shared\/wire\.ts\n\n- 增删行：\+2 \/ -0/);
  for (const name of ["fetchExample", "default", "renamed", "mutable"]) assert.ok(report.includes(name));
  await assert.rejects(renderDrift("--output=bad", dir), /--since/);
  await assert.rejects(renderDrift("HEAD; echo bad", dir), /--since/);
  await assert.rejects(renderDrift("HEAD..HEAD", dir), /--since/);
  assert.match(await renderDrift("HEAD~1", dir), /shared\/deleted/);
});
